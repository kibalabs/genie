    FILE_EXTENSIONS: list[str]
    AUTOGENERATED_NOTICE: str

    def boolean_type(self, isNullable: bool) -> str:
        raise NotImplementedError

    def date_type(self, isNullable: bool) -> str:
        raise NotImplementedError

