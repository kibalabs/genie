    def mapping_type(self, isNullable: bool, keyType: str, valueType: str) -> str:
        raise NotImplementedError

    def json_type(self, isNullable: bool) -> str:
        raise NotImplementedError

    def list_type(self, isNullable: bool, listItemType: str) -> str:
        raise NotImplementedError

    def struct_type(self, isNullable: bool) -> str:
        raise NotImplementedError

    def long_integer_type(self, isNullable: bool) -> str:
        raise NotImplementedError

